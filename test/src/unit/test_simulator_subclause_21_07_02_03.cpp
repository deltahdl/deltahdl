TEST_F(VcdKeywordCommandsE2E, SubInstanceVariablesAreDeclaredInTheirOwnScope) {
  auto content = RunVcd(
      "module leaf; logic [3:0] x = 1; endmodule\n"
      "module sub; logic [7:0] deep = 3; leaf l(); endmodule\n"
      "module t;\n"
      "  sub u();\n"
      "  logic [7:0] shallow = 1;\n"
      "endmodule\n");
  auto lines = AllLines(content);
  EXPECT_FALSE(FindVarLine(lines, "deep").empty()) << content;
  EXPECT_FALSE(FindVarLine(lines, "x").empty()) << content;
  EXPECT_TRUE(FindVarLine(lines, "u.deep").empty()) << content;
  EXPECT_TRUE(FindVarLine(lines, "u.l.x").empty()) << content;
  size_t t_scope = content.find("$scope module t $end");
  size_t u_scope = content.find("$scope module u $end");
  size_t l_scope = content.find("$scope module l $end");
  ASSERT_NE(u_scope, std::string::npos) << content;
  ASSERT_NE(l_scope, std::string::npos) << content;
  EXPECT_LT(t_scope, u_scope);
  EXPECT_LT(u_scope, content.find(" deep $end"));
  EXPECT_LT(content.find(" deep $end"), l_scope);
  EXPECT_LT(l_scope, content.find(" x $end"));
  EXPECT_EQ(CountLine(lines, "$upscope $end"), 3u) << content;
  EXPECT_LT(content.rfind("$upscope $end"), content.find("$enddefinitions"));
}

class VcdScopeKindSim : public VcdDumpFromSourceTestBase {};

TEST_F(VcdScopeKindSim, BlocksAndTasksOpenScopesOfTheirOwnKind) {
  RunSource(
      "module m;\n"
      "  task tk; int tv; tv = 7; endtask\n"
      "  initial begin : b1\n"
      "    int bv;\n"
      "    bv = 1;\n"
      "    fork : f1\n"
      "      int fv;\n"
      "      fv = 2;\n"
      "    join\n"
      "    tk();\n"
      "    #2;\n"
      "  end\n"
      "  initial begin\n"
      "    #1;\n"
      "    $dumpfile(\"kinds.vcd\");\n"
      "    $dumpvars;\n"
      "  end\n"
      "endmodule\n");
  const std::string kDump = DumpFile("kinds.vcd");
  size_t begin_at = kDump.find("$scope begin b1 $end");
  size_t fork_at = kDump.find("$scope fork f1 $end");
  size_t task_at = kDump.find("$scope task tk $end");
  ASSERT_NE(begin_at, std::string::npos) << kDump;
  ASSERT_NE(fork_at, std::string::npos) << kDump;
  ASSERT_NE(task_at, std::string::npos) << kDump;
  EXPECT_NE(kDump.find(" bv $end", begin_at), std::string::npos) << kDump;
  EXPECT_NE(kDump.find(" fv $end", fork_at), std::string::npos) << kDump;
  EXPECT_NE(kDump.find(" tv $end", task_at), std::string::npos) << kDump;
  EXPECT_LT(begin_at, fork_at) << kDump;
  EXPECT_EQ(kDump.find("$scope module b1"), std::string::npos) << kDump;
  EXPECT_EQ(kDump.find("$scope module tk"), std::string::npos) << kDump;
}

class VcdPackageScopeSim : public VcdDumpFromSourceTestBase {};

TEST_F(VcdPackageScopeSim, APackageIsATopLevelScopeOfTheDump) {
  RunSource(
      "package p;\n"
      "  int v = 3;\n"
      "endpackage\n"
      "module m;\n"
      "  int w = 1;\n"
      "  initial begin\n"
      "    $dumpfile(\"pkg.vcd\");\n"
      "    $dumpvars;\n"
      "    #1 p::v = 4;\n"
      "  end\n"
      "endmodule\n");
  const std::string kDump = DumpFile("pkg.vcd");
  size_t at = kDump.find("$scope module p $end");
  ASSERT_NE(at, std::string::npos) << kDump;
  int depth = 0;
  for (size_t pos = kDump.find("$scope"); pos < at;
       pos = kDump.find("$scope", pos + 1)) {
    ++depth;
  }
  for (size_t pos = kDump.find("$upscope"); pos < at;
       pos = kDump.find("$upscope", pos + 1)) {
    --depth;
  }
  EXPECT_EQ(depth, 0) << kDump;
  EXPECT_NE(kDump.find(" v $end", at), std::string::npos) << kDump;
}


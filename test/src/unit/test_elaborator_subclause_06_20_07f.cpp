TEST(DollarConstantElaboration,
     DollarSelectThroughANameDesignatingNothingLeavesThatNameReported) {
  ElabFixture f;
  Elaborate(
      "module top;\n"
      "  localparam A = B;\n"
      "  localparam B = A;\n"
      "  typedef int T;\n"
      "  T v;\n"
      "  struct { int f; } s;\n"
      "  int x;\n"
      "  int q [$];\n"
      "  nomod u ();\n"
      "  virtual noifc vi;\n"
      "  function void NoClass::m();\n"
      "    x = x[$];\n"
      "    x = q[$];\n"
      "  endfunction\n"
      "  initial begin\n"
      "    x = A[$];\n"
      "    x = v.m[$];\n"
      "    x = s.nosuch[$];\n"
      "    x = nosuch.v[$];\n"
      "    x = nopkg::v[$];\n"
      "    x = u.v[$];\n"
      "    x = vi.v[$];\n"
      "  end\n"
      "endmodule\n",
      f);
  const auto& diags = f.diag.Diagnostics();
  EXPECT_TRUE(
      ReportedError(diags, "'B' is used before its declaration", 2, "6.5"));
  EXPECT_TRUE(ReportedError(diags, "unknown module 'nomod'", 9, "23.3.2"));
  EXPECT_TRUE(ReportedError(
      diags, "unknown interface 'noifc' in virtual interface declaration", 10,
      "25.9"));
  EXPECT_TRUE(ReportedError(
      diags, "'m' is not a built-in method of the integral or real value 'v'",
      17, "23.7"));
  EXPECT_TRUE(ReportedError(
      diags, "the structure of 's' has no member named 'nosuch'", 18, "23.7"));
  EXPECT_TRUE(ReportedError(
      diags, "hierarchical name 'nosuch' resolves to no declaration", 19,
      "23.8"));
  EXPECT_TRUE(ReportedError(
      diags, "reference to unresolved package or scope 'nopkg'", 20, "26.3"));
  ExpectDollarReportedOnlyOn(f, {12}, {13});
}


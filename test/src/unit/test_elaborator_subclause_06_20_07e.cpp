TEST(DollarConstantElaboration,
     DollarInANonQueueSelectNestedInAQueueIndexIsReported) {
  ElabFixture f;
  Elaborate(
      "typedef int UT;\n"
      "class C;\n"
      "  int cq [$], ca [4];\n"
      "  UT ct;\n"
      "  int x;\n"
      "  function void f();\n"
      "    x = cq[ca[$]];\n"
      "    x = cq[ct[$]];\n"
      "    x = cq[cq[$]];\n"
      "    x = ca[cq[$]];\n"
      "  endfunction\n"
      "endclass\n"
      "function automatic int uf();\n"
      "  int fq [$], fa [4];\n"
      "  uf = fq[fa[$]];\n"
      "  uf = fq[fq[$]];\n"
      "endfunction\n"
      "module top;\n"
      "  int q [$], a [4], x;\n"
      "  typedef int T;\n"
      "  T t;\n"
      "  initial begin\n"
      "    x = q[a[$]];\n"
      "    x = q[t[$]];\n"
      "    x = q[a[$ - 1]];\n"
      "    x = q[q[$]];\n"
      "    x = a[q[$]];\n"
      "    x = q[q[$ - 1]];\n"
      "  end\n"
      "endmodule\n",
      f);
  ExpectDollarReportedOnlyOn(f, {7, 8, 15, 23, 24, 25},
                             {9, 10, 16, 26, 27, 28});
}

